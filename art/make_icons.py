"""Regenerates the launcher icon, round icon and TV banner from the vector mark
(app/src/main/res/drawable/ic_launcher.xml as of 0d205b8, the highest-resolution source).
Run: /workspace/tools/artvenv/bin/python make_icons.py <res dir> <out dir> [--before]"""
import io, re, sys, xml.etree.ElementTree as ET
import cairosvg
from PIL import Image, ImageDraw, ImageFont

A = '{http://schemas.android.com/apk/res/android}'
BG = '#080D1C'
FONT = '/usr/share/fonts/truetype/sand-box/google/Open Sans/OpenSans-VariableFont_wdth,wght.ttf'
# Mark bounds in its 48-unit group (strokes included).
BX0, BY0, BX1, BY1 = 10.3, 6.6, 48.6, 43.5
# Centre of the smallest circle around the mark (radius 23.85 units): the adaptive icon is centred there.
CX, CY = 28.8, 25.8

def mark_paths(src):
    root = ET.parse(src).getroot()
    group = root.find('group')
    return [dict((k.replace(A, ''), v) for k, v in p.attrib.items()) for p in group.findall('path')]

def svg_path(p):
    out = [f'd="{p["pathData"]}"']
    fill = p.get('fillColor', '#00000000')
    out.append('fill="none"' if fill == '#00000000' else f'fill="{fill}"')
    if 'fillAlpha' in p: out.append(f'fill-opacity="{p["fillAlpha"]}"')
    if 'strokeColor' in p:
        out += [f'stroke="{p["strokeColor"]}"', f'stroke-width="{p.get("strokeWidth", "1")}"']
        if 'strokeLineCap' in p: out.append(f'stroke-linecap="{p["strokeLineCap"]}"')
        if 'strokeAlpha' in p: out.append(f'stroke-opacity="{p["strokeAlpha"]}"')
    return '<path ' + ' '.join(out) + '/>'

def vector_path(p, indent='        '):
    lines = [f'{indent}<path']
    for k in ['fillColor', 'fillAlpha', 'pathData', 'strokeWidth', 'strokeColor', 'strokeLineCap', 'strokeAlpha']:
        if k in p: lines.append(f'{indent}    android:{k}="{p[k]}"')
    lines[-1] += ' />'
    return '\n'.join(lines)

def render_mark(paths, height_px):
    """The mark alone (transparent), cropped to its bounds, [height_px] tall."""
    s = height_px / (BY1 - BY0)
    w = round((BX1 - BX0) * s)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{height_px}" viewBox="{BX0} {BY0} {BX1-BX0} {BY1-BY0}">'
           + ''.join(svg_path(p) for p in paths) + '</svg>')
    return Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode(), output_width=w, output_height=height_px))).convert('RGBA')

def font(size, weight):
    f = ImageFont.truetype(FONT, size)
    f.set_variation_by_axes([weight, 100])  # Open Sans axes: weight, width
    return f

def banner(paths, w, h):
    """Mark at ~84% of the height, wordmark beside it; small margins."""
    img = Image.new('RGBA', (w, h), BG)
    mark = render_mark(paths, round(h * 0.82))
    pad = round(w * 0.035)
    gap = round(w * 0.02)
    room = w - 2 * pad - mark.width - gap
    # Largest wordmark that fits the room.
    size = h
    while size > 6:
        a, b = font(size, 500), font(size, 700)
        tw = a.getlength('Enigma') + b.getlength('Cast')
        if tw <= room: break
        size -= 1
    total = mark.width + gap + tw
    x = round((w - total) / 2)
    img.alpha_composite(mark, (x, round((h - mark.height) / 2)))
    d = ImageDraw.Draw(img)
    tx = x + mark.width + gap
    asc, desc = a.getmetrics()
    top = a.getbbox('EnigmaCast')
    ty = round(h / 2 - (top[1] + top[3]) / 2)
    d.text((tx, ty), 'Enigma', font=a, fill='#E8EEF8')
    d.text((tx + a.getlength('Enigma'), ty), 'Cast', font=b, fill='#24D9FF')
    return img

FG_SCALE = 1.36  # the mark's enclosing circle becomes 32.4 dp radius: inside the 66 dp safe zone (was 1.0, 23.9 dp)

def foreground_xml(paths, scale, background=False):
    tx, ty = 54 - CX * scale, 54 - CY * scale
    bg = (f'    <path\n        android:fillColor="{BG}"\n        android:pathData="M0,0h108v108h-108z" />\n') if background else ''
    body = '\n'.join(vector_path(p) for p in paths)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by art/make_icons.py from the EnigmaCast mark; edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{bg}    <group
        android:scaleX="{scale}"
        android:scaleY="{scale}"
        android:translateX="{tx:.2f}"
        android:translateY="{ty:.2f}">
{body}
    </group>
</vector>
'''

def icon_png(paths, px, scale, mask):
    """Preview: the adaptive icon as a launcher shows it (72 of 108 dp visible, masked)."""
    full = round(px * 108 / 72)
    s = full / 108
    img = Image.new('RGBA', (full, full), BG)
    mark = render_mark(paths, round((BY1 - BY0) * scale * s))
    k = mark.height / (BY1 - BY0)
    img.alpha_composite(mark, (round(full / 2 - (CX - BX0) * k), round(full / 2 - (CY - BY0) * k)))
    off = (full - px) // 2
    img = img.crop((off, off, off + px, off + px))
    m = Image.new('L', (px, px), 0)
    if mask == 'circle': ImageDraw.Draw(m).ellipse((0, 0, px - 1, px - 1), fill=255)
    else: ImageDraw.Draw(m).rounded_rectangle((0, 0, px - 1, px - 1), radius=px // 6, fill=255)
    out = Image.new('RGBA', (px, px), (0, 0, 0, 0)); out.paste(img, (0, 0), m)
    # Safe zone (66 dp circle) outline for checking.
    return out

if __name__ == '__main__':
    res, out = sys.argv[1], sys.argv[2]
    paths = mark_paths(f'{res}/drawable/ic_launcher.xml')
    if '--write' in sys.argv:
        for d, (w, h) in {'mdpi': (160, 90), 'hdpi': (240, 135), 'xhdpi': (320, 180), 'xxhdpi': (480, 270), 'xxxhdpi': (640, 360)}.items():
            import os; os.makedirs(f'{res}/drawable-{d}', exist_ok=True)
            banner(paths, w, h).convert('RGB').save(f'{res}/drawable-{d}/tv_banner.png', optimize=True)
        open(f'{res}/drawable/ic_launcher_foreground.xml', 'w').write(foreground_xml(paths, FG_SCALE))
        open(f'{res}/drawable/ic_launcher.xml', 'w').write(foreground_xml(paths, FG_SCALE, background=True))
    else:
        b = banner(paths, 640, 360); b.save(f'{out}/launcher-after-banner.png')
        icon_png(paths, 192, FG_SCALE, 'circle').save(f'{out}/launcher-after-round.png')
        icon_png(paths, 192, FG_SCALE, 'square').save(f'{out}/launcher-after-square.png')
        # Before: the old drawable (mark at scale 1, translate 30/30 → centred on its group's 24/24).
        CX, CY = 24, 24
        icon_png(paths, 192, 1.0, 'circle').save(f'{out}/launcher-before-round.png')
